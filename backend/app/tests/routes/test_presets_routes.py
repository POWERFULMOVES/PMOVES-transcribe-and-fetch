class MockSupabaseResponse:
    def __init__(self, data=None, error=None, count=None):
        self.data = data
        self.error = error
        self.count = count

    # Helper to mimic Pydantic model for error attribute if necessary
    # Supabase client errors might have a 'message' attribute
    def __getattr__(self, name):
        if name == 'message' and self.error and isinstance(self.error, str):
            return self.error
        raise AttributeError(f"'{type(self).__name__}' object has no attribute '{name}'")


