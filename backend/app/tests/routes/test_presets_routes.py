def test_create_preset_success(client: TestClient, mock_supabase_client_fixture):
    _, mock_execute = mock_supabase_client_fixture

    preset_to_create_data = create_sample_preset_data(USER_ID_1)
    # What the DB insert call would return (includes DB-set fields like preset_id, created_at, updated_at)
    # For this test, we assume the input `created_by` is used and returned.
    # The `preset_id` is generated by DB, so client doesn't send it.
    # `created_at`, `updated_at` also by DB.

    # Mock the response from supabase.insert().execute()
    # The data returned by Supabase after insert includes the full row
    mock_db_response_data = {
        "preset_id": uuid.uuid4(), # Let's assume DB generates this
        "preset_name": preset_to_create_data["preset_name"],
        "description": preset_to_create_data["description"],
        "version": preset_to_create_data["version"],
        "crawl_tool": preset_to_create_data["crawl_tool"],
        "strategy_definition": preset_to_create_data["strategy_definition"],
        "target_capability": preset_to_create_data["target_capability"],
        "tags": preset_to_create_data["tags"],
        "created_by": str(preset_to_create_data["created_by"]), # Ensure it's string for comparison if needed
        "created_at": datetime.now(timezone.utc).isoformat(),
        "updated_at": datetime.now(timezone.utc).isoformat(),
    }
    mock_execute.return_value = MockSupabaseResponse(data=[mock_db_response_data])

    payload = {
        "preset_name": preset_to_create_data["preset_name"],
        "description": preset_to_create_data["description"],
        "strategy_definition": preset_to_create_data["strategy_definition"],
        "target_capability": preset_to_create_data["target_capability"],
        "tags": preset_to_create_data["tags"],
        "created_by": str(USER_ID_1), # Client sends this
        # version is optional in CrawlPresetCreate, defaults in base model
    }

    response = client.post("/api/presets", json=payload)

    assert response.status_code == 201
    data = response.json()
    assert data["preset_name"] == payload["preset_name"]
    assert data["created_by"] == payload["created_by"]
    assert "preset_id" in data
    mock_execute.assert_called_once()


