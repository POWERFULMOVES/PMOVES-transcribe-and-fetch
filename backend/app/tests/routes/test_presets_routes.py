def test_get_preset_invalid_uuid_format(client: TestClient):
    # The route uses Union[UUID, str]. If it's not a valid UUID, it's treated as a name.
    # If it's syntactically invalid FOR A UUID but could be a name, it will proceed to query by name.
    # True UUID validation error (422) from FastAPI path converter happens if the type hint is just UUID
    # and an invalid UUID string is provided.
    # Given current Union[UUID, str], a truly "invalid format" test for UUID that results in 422
    # at path conversion level is not straightforward unless the string is also problematic for path parsing.
    # For this test, we'll assume an ID that's not a UUID and not found as a name.
    _, mock_execute = mock_supabase_client_fixture # Need this to avoid errors if it tries to call
    mock_execute.return_value = MockSupabaseResponse(data=[])

    response = client.get("/api/presets/this-is-not-a-uuid-and-not-a-name")
    assert response.status_code == 404 # Will be treated as a name, and not found.
    mock_execute.assert_called_once() # Verifies it went to the DB
